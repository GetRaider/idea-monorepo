export function translationStub({
  word,
  nativeLanguage,
}: {
  word: string;
  nativeLanguage: NativeLanguage;
}): string {
  const lemma = word.trim().toLowerCase();

  const hit = dictionary[nativeLanguage]?.[lemma];
  if (hit) return hit;

  return `[${nativeLanguage}] ${word}`;
}

